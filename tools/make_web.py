#!/usr/bin/env python3
"""Build the GUI pages from web/index.html (run after editing it):
   src/web_page.h  - the page the tester serves over Wi-Fi / Ethernet
   web/ble.html    - the same GUI over Bluetooth; host it on any https:// site
"""
import os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
html = open(os.path.join(root, "web", "index.html"), encoding="utf-8").read()

lines = []
for ln in html.splitlines():
    ln = ln.replace("\\", "\\\\").replace('"', '\\"')
    lines.append('"' + ln + '\\n"')
out = "// generated by tools/make_web.py from web/index.html - edit that file, not this one\n#pragma once\nstatic const char INDEX_HTML[] =\n" + "\n".join(lines) + ";\n"
open(os.path.join(root, "src", "web_page.h"), "w", encoding="utf-8").write(out)
print("web_page.h: %d bytes of HTML" % len(html.encode("utf-8")))

shim = open(os.path.join(root, "web", "ble_shim.html"), encoding="utf-8").read()
i = html.index("<script>")              # shim must run before the GUI's own script
ble = html[:i] + shim + "\n" + html[i:]
ble = ble.replace("<title>NetAlly Buster</title>", "<title>NetAlly Buster (Bluetooth)</title>", 1)
open(os.path.join(root, "web", "ble.html"), "w", encoding="utf-8").write(ble)
print("ble.html:    %d bytes" % len(ble.encode("utf-8")))
